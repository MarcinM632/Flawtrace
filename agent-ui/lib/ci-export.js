// Eksport konfiguracji CI dla wygenerowanego projektu testów. Flawtrace pisze gotowy projekt (np. TS Playwright);
// wzorem frameworka e2e (testy żyją jako kod w repo klienta i odpalają się w JEGO CI) dajemy klientowi gotowy plik
// pipeline'u — GitHub Actions albo GitLab CI — który instaluje zależności, przeglądarki i uruchamia testy na jego
// adresie (BASE_URL z sekretu), z artefaktem raportu. Czysty generator łańcuchów, bez efektów ubocznych.

// Komenda uruchomienia per stos (zgodna z lib/stacks.js).
const RUN = {
  'ts-playwright': { install: 'npm ci || npm install', browsers: 'npx playwright install --with-deps', test: 'npx playwright test', report: 'playwright-report', node: true },
  python: { install: 'pip install -r requirements.txt && playwright install --with-deps', browsers: '', test: 'pytest -q', report: 'report', node: false },
  cypress: { install: 'npm ci || npm install', browsers: '', test: 'npx cypress run', report: 'cypress/results', node: true },
};

const stackOf = (stack) => RUN[stack] || RUN['ts-playwright'];

/** GitHub Actions workflow (.github/workflows/e2e.yml). */
function githubActions(stack = 'ts-playwright') {
  const s = stackOf(stack);
  const steps = [
    '      - uses: actions/checkout@v4',
    s.node ? '      - uses: actions/setup-node@v4\n        with:\n          node-version: 20' : '      - uses: actions/setup-python@v5\n        with:\n          python-version: \'3.12\'',
    `      - run: ${s.install}`,
    ...(s.browsers ? [`      - run: ${s.browsers}`] : []),
    `      - run: ${s.test}\n        env:\n          BASE_URL: \${{ secrets.BASE_URL }}`,
    `      - uses: actions/upload-artifact@v4\n        if: always()\n        with:\n          name: test-report\n          path: ${s.report}`,
  ];
  return `# Generated by Flawtrace. Set the BASE_URL secret to your app's URL.
name: e2e
on:
  push:
  pull_request:
jobs:
  test:
    runs-on: ubuntu-latest
    steps:
${steps.join('\n')}
`;
}

/** GitLab CI pipeline (.gitlab-ci.yml). */
function gitlabCi(stack = 'ts-playwright') {
  const s = stackOf(stack);
  const image = s.node ? 'node:20' : 'python:3.12';
  const scripts = [s.install, ...(s.browsers ? [s.browsers] : []), `BASE_URL="$BASE_URL" ${s.test}`];
  return `# Generated by Flawtrace. Set the BASE_URL CI/CD variable to your app's URL.
e2e:
  image: ${image}
  script:
${scripts.map((c) => `    - ${c}`).join('\n')}
  artifacts:
    when: always
    paths:
      - ${s.report}
`;
}

/** Jeden plik dla wybranego providera ('github' | 'gitlab'); zwraca { path, content }. */
function forProvider(provider, stack = 'ts-playwright') {
  return provider === 'gitlab'
    ? { path: '.gitlab-ci.yml', content: gitlabCi(stack) }
    : { path: '.github/workflows/e2e.yml', content: githubActions(stack) };
}

module.exports = { githubActions, gitlabCi, forProvider, RUN };
