// Współdzielony raport przebiegu w Markdown — jedna zwięzła treść, którą da się wkleić do PR/MR, Slacka czy maila,
// albo wysłać jako komentarz do merge requesta. Wzorowane na reporterach frameworka e2e (reporter HTML + komentarz
// PR): dotąd raporty żyły tylko w UI aplikacji. To czysty formatter mety przebiegu (lib/run-agent zapisuje meta.*),
// deterministyczny i testowalny; samo wysłanie to osobna, cienka warstwa (postMrComment), która go używa.
const SEV_EMOJI = { critical: '🔴', high: '🟠', medium: '🟡', low: '⚪' };
const STATUS_EMOJI = { SUKCES: '✅', 'RAPORT OK': '✅', done: '✅', BŁĄD: '❌', failed: '❌', error: '❌', NIEWERYFIKOWALNE: '⚠️', PRZERWANO: '⏹️', cancelled: '⏹️', running: '⏳' };
const trim = (s, n) => { const t = String(s || '').replace(/\s+/g, ' ').trim(); return t.length > n ? t.slice(0, n - 1) + '…' : t; };

// Pierwsza linia WYNIK:/WYNIK z raportu (jeśli jest) — ludzkie podsumowanie jednym zdaniem.
function resultLine(report) {
  const m = String(report || '').match(/^\s*\**(?:WYNIK|RESULT|SUMMARY)\**\s*:\s*(.+)$/im);
  return m ? trim(m[1], 300) : '';
}
function statusMark(meta) {
  const s = (meta.reportStatus || '').toUpperCase().replace(/^STATUS:\s*/, '').split(/\s/)[0] || meta.status || '';
  for (const [k, e] of Object.entries(STATUS_EMOJI)) if (s === k.toUpperCase() || meta.status === k) return `${e} ${meta.reportStatus ? meta.reportStatus.replace(/^STATUS:\s*/i, '') : meta.status}`;
  return meta.reportStatus || meta.status || 'unknown';
}

// Linie faktów liczonych przez aplikację (pentest: pokrycie API, skan kodu, skan transportu).
function factLines(meta) {
  const out = [];
  const c = meta.coverage;
  if (c && c.available && c.total) out.push(`**Endpoint coverage:** ${c.covered}/${c.total} (${c.pct}%)${c.pct < 100 && (c.uncovered || []).length ? ` — ${c.uncovered.length} never exercised` : ''}`);
  const rs = meta.repoScan;
  if (rs && rs.available) { const k = rs.counts || {}; out.push(k.total ? `**Static repo scan:** ${k.critical || 0} critical, ${k.high || 0} high, ${k.medium || 0} medium, ${k.low || 0} low (secrets ${k.secret || 0}, SAST ${k.sast || 0}, SCA ${k.sca || 0})` : '**Static repo scan:** clean'); }
  const t = meta.transport;
  if (t && t.available) { const k = t.counts || {}; out.push(k.total ? `**Transport/HTTP:** ${k.critical || 0} critical, ${k.high || 0} high, ${k.medium || 0} medium, ${k.low || 0} low` : '**Transport/HTTP:** clean'); }
  const en = meta.engine;
  if (en) out.push(`**Pentest engine:** engagement ${en.id} — ${en.verified} finding(s) proven by the app, checklist coverage ${en.coverage}% (${en.pending} item(s) left)`);
  const a = meta.audit;
  if (a && a.issues) out.push(a.issues.length ? `**Report check:** ${a.issues.length} unresolved problem(s)` : '**Report check:** passed');
  return out;
}

// Najpoważniejsze znaleziska z faktów aplikacji (skan kodu + transport), do sekcji szczegółów.
function topFindings(meta, max) {
  const all = [];
  for (const f of (meta.repoScan && meta.repoScan.findings) || []) all.push({ ...f, origin: 'code' });
  for (const f of (meta.transport && meta.transport.findings) || []) all.push({ ...f, origin: 'transport' });
  const rank = { critical: 0, high: 1, medium: 2, low: 3 };
  all.sort((a, b) => (rank[a.severity] - rank[b.severity]));
  return all.filter((f) => f.severity === 'critical' || f.severity === 'high').slice(0, max).map((f) =>
    `- ${SEV_EMOJI[f.severity] || ''} **${f.severity}** · ${f.origin === 'code' ? `${f.rule} — \`${f.file || ''}${f.line ? ':' + f.line : ''}\`` : `${f.rule} (${f.cwe || ''})`}`);
}

/** Jedna linia nagłówka — do listy przebiegów albo powiadomienia. */
function summaryLine(meta) {
  return `Flawtrace · ${meta.label || meta.agent || 'run'}: ${statusMark(meta)}${meta.ticket ? ` · ${trim(meta.ticket, 60)}` : ''}`;
}

/** Pełny raport w Markdown. opts.maxFindings (domyślnie 10), opts.link (URL do przebiegu w aplikacji). */
function toMarkdown(meta, opts = {}) {
  if (!meta) return '';
  const max = opts.maxFindings || 10;
  const lines = [`### Flawtrace — ${meta.label || meta.agent || 'run'}: ${statusMark(meta)}`];
  if (meta.ticket) lines.push(`**Task:** ${trim(meta.ticket, 200)}`);
  const rl = resultLine(meta.report);
  if (rl) lines.push('', rl);
  const facts = factLines(meta);
  if (facts.length) lines.push('', ...facts.map((f) => `- ${f}`));
  const finds = topFindings(meta, max);
  if (finds.length) lines.push('', '<details><summary>Top findings</summary>', '', ...finds, '</details>');
  const cost = typeof meta.costUsd === 'number' && meta.costUsd > 0 ? ` · $${meta.costUsd.toFixed(2)}` : '';
  lines.push('', `_Generated by Flawtrace${opts.link ? ` · [open the run](${opts.link})` : ''}${cost}._`);
  return lines.join('\n');
}

/**
 * Wyślij raport jako komentarz do merge requesta (opcjonalna, cienka warstwa). `poster` wstrzykiwalny dla testów;
 * w produkcji to wywołanie API GitLab (lib/gitlab). Zwraca { ok, skipped?, error? }.
 */
async function postMrComment(meta, { projectId, mrIid, poster, opts } = {}) {
  if (!projectId || !mrIid) return { ok: false, skipped: true, reason: 'no merge request target' };
  const body = toMarkdown(meta, opts);
  try { await poster({ projectId, mrIid, body }); return { ok: true }; }
  catch (e) { return { ok: false, error: String(e && e.message || e) }; }
}

module.exports = { toMarkdown, summaryLine, postMrComment, _resultLine: resultLine, _factLines: factLines, _topFindings: topFindings };
